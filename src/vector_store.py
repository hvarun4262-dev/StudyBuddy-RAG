import os
import pickle
import faiss
import numpy as np

class FaissVectorStore:
    def __init__(self, persist_dir="faiss_store"):
        self.persist_dir = persist_dir
        self.index = None
        self.metadata = []
        os.makedirs(self.persist_dir, exist_ok=True)

    def build_from_documents(self, embeddings, chunks):
        dimension = embeddings.shape[1]
        self.index = faiss.IndexFlatL2(dimension)
        
        self.index.add(np.array(embeddings).astype('float32'))
        self.metadata = chunks
        self.save()
        print(f"Built FAISS vector index with {self.index.ntotal} vectors.")

    def save(self):
        faiss.write_index(self.index, os.path.join(self.persist_dir, "faiss.index"))
        with open(os.path.join(self.persist_dir, "metadata.pickle"), "wb") as f:
            pickle.dump(self.metadata, f)

    def load(self):
        index_path = os.path.join(self.persist_dir, "faiss.index")
        metadata_path = os.path.join(self.persist_dir, "metadata.pickle")
        
        if not os.path.exists(index_path):
            raise FileNotFoundError("FAISS index not found. Build the index first.")
        if not os.path.exists(metadata_path):
            raise FileNotFoundError("Chunk metadata not found. Build the index first.")

        self.index = faiss.read_index(index_path)
        
        # Only load pickle files generated by your own trusted application.
        with open(metadata_path, "rb") as f:
            self.metadata = pickle.load(f)

    def similarity_search(self, query_embedding, top_k=4, distance_threshold=None):
        distances, indices = self.index.search(
            np.array([query_embedding]).astype('float32'), top_k
        )
        
        results = []
        for i, idx in enumerate(indices[0]):
            distance = distances[0][i]
            
            # Distance relevance check: skip chunk if distance exceeds your threshold
            if distance_threshold is not None and distance > distance_threshold:
                continue
                
            if idx != -1 and idx < len(self.metadata):
                results.append(self.metadata[idx])
        return results